/**
 * Las variables declaradas para una `key`, o `[]` si la plantilla no está en el
 * catálogo. Devolver `[]` y no `undefined` es a propósito: el call site pinta una
 * lista, y una plantilla fuera del catálogo tiene que degradar a "sin variables
 * declaradas", no romper la pantalla.
 */
export function variablesForKey(key: string | undefined | null): EmailTemplateVariable[] {
  if (!key) return [];
  return EMAIL_TEMPLATE_VARIABLES[key] ?? [];
}
