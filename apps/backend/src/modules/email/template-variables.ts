/**
 * Catálogo de variables por plantilla de email — qué datos recibe cada mail, con
 * su descripción.
 *
 * ¿Por qué existe, si el seed ya las declara? Porque la FILA de la base puede no
 * declararlas. Cualquier plantilla creada fuera del seed, o migrada desde el
 * editor visual, nace con `variables` vacío — y la pantalla del admin gatea su
 * editor de variables con `variables.length === 0`. Resultado: la pantalla se ve
 * vacía y el operador no tiene dónde ver ni tocar los valores, aunque el backend
 * sepa perfectamente cuáles son. Derivando la lista del código, una fila
 * incompleta ya no puede esconder el editor.
 *
 * NO reemplaza a las listas del seed: el seed sigue escribiendo su propia copia
 * en la fila, y esta es el respaldo. Un test cruza este catálogo contra las keys
 * de `admin/lib/email-events-catalog.ts` para que una key nueva sin variables
 * falle en CI en vez de aparecer como una pantalla vacía.
 *
 * Es DATA PURA (sin imports de `@medusajs`) para que la puedan leer las tres
 * puntas: el seed, las rutas del admin y el bundle del admin.
 */

