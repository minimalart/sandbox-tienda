export function usePrivacyTranslation() {
  const { i18n } = useTranslation();
  for (const [lang, resource] of Object.entries({ en, es })) {
    if (!i18n.hasResourceBundle(lang, 'marketingPrivacy'))
      i18n.addResourceBundle(lang, 'marketingPrivacy', resource);
  }
  return {
    t: (key: keyof typeof en) => String(i18n.t(key, { ns: 'marketingPrivacy' })),
    lang: i18n.language.startsWith('es') ? ('es' as const) : ('en' as const),
  };
}
