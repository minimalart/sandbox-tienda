const fs = require('node:fs');
const path = require('node:path');

function renderPrivacySlot(ids) {
  const consent = ids.includes('consent-management');
  const analytics = ids.includes('ga4');
  const clarity = ids.includes('clarity');
  return [
    "'use client'",
    "import { useMemo, type ReactNode } from 'react'",
    clarity ? "import ClarityAnalytics, { clarityService } from './analytics/clarity'" : '',
    "import type { PrivacyConfiguration, ConsentAwareService } from './consent/contract'",
    consent ? "import ConsentProvider from './consent/provider'" : '',
    analytics ? "import GoogleAnalytics from './analytics/google-analytics'" : '',
    analytics && consent ? "import { googleAnalyticsService } from './analytics/runtime'" : '',
    'export default function PrivacySlot({ config, children }: { config: PrivacyConfiguration; children: ReactNode }) {',
    consent
      ? `const services = useMemo<ConsentAwareService[]>(() => [${analytics ? '...(config.analytics?.enabled ? [googleAnalyticsService] : []),' : ''} ${clarity ? '...(config.clarity?.enabled ? [clarityService] : [])' : ''}], [config.analytics?.enabled, config.clarity?.enabled]);`
      : '',
    `return ${consent ? '<ConsentProvider key={config.siteId} settings={config.consent} siteId={config.siteId} services={services}>' : '<>'}`,
    clarity ? '<ClarityAnalytics config={config.clarity} siteId={config.siteId} />' : '',
    analytics ? '<GoogleAnalytics config={config.analytics} />' : '',
    `{children}${consent ? '</ConsentProvider>' : '</>'}`,
    '}',
    '',
  ]
    .filter(Boolean)
    .join('\n');
}

function writePrivacyIntegrations(root, ids) {
  for (const [extension, page] of [['clarity', 'clarity'], ['google-merchant', 'google-merchant']]) {
    if (!ids.includes(extension)) fs.rmSync(path.join(root, 'apps/backend/src/admin/routes/marketing-privacy', page), { recursive: true, force: true });
  }
  fs.writeFileSync(
    path.join(root, 'apps/storefront/src/lib/privacy-slot.tsx'),
    renderPrivacySlot(ids)
  );
  fs.writeFileSync(
    path.join(root, 'apps/backend/src/lib/marketing-privacy-capabilities.ts'),
    `// Generated by project-composer.\nexport const marketingPrivacyCapabilities = ${JSON.stringify({ consent: ids.includes('consent-management'), analytics: ids.includes('ga4'), newsletter: ids.includes('newsletter'), clarity: ids.includes('clarity'), merchant: ids.includes('google-merchant') })}\n`
  );
  if (!ids.includes('consent-management')) {
    const file = path.join(root, 'apps/storefront/package.json');
    const pkg = JSON.parse(fs.readFileSync(file, 'utf8'));
    delete pkg.dependencies['vanilla-cookieconsent'];
    delete pkg.scripts['test:privacy:browser'];
    fs.writeFileSync(file, JSON.stringify(pkg, null, 2) + '\n');
    const lock = path.join(root, 'pnpm-lock.yaml');
    if (fs.existsSync(lock))
      fs.writeFileSync(
        lock,
        fs
          .readFileSync(lock, 'utf8')
          .replace(
            /      vanilla-cookieconsent:\r?\n        specifier: [^\n]+\r?\n        version: [^\n]+\r?\n/,
            ''
          )
      );
  }
}
module.exports = { renderPrivacySlot, writePrivacyIntegrations };
